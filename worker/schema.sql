-- 検索結果の保存（同じ条件で再利用）
CREATE TABLE IF NOT EXISTS cache (k TEXT PRIMARY KEY, body TEXT NOT NULL, expires INTEGER NOT NULL);
-- タイトルの和訳（動画IDごと）
CREATE TABLE IF NOT EXISTS trans (vid TEXT PRIMARY KEY, ja TEXT NOT NULL);
-- 1日の検索回数
CREATE TABLE IF NOT EXISTS quota (day TEXT PRIMARY KEY, n INTEGER NOT NULL);
-- 連続呼び出しの制限
CREATE TABLE IF NOT EXISTS rl (k TEXT PRIMARY KEY, n INTEGER NOT NULL, exp INTEGER NOT NULL);
